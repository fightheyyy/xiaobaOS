import * as fs from 'node:fs';
import * as path from 'node:path';
import { AgentCase, CaseSet, ReplayResult, VerifierResult } from './evaluation';
import { MemoryFinalizer } from '../utils/memory-finalizer';

export type CollaborationCategory = 'async' | 'events' | 'memory';
export type CollaborationMode = 'candidate' | 'baseline';
export const COLLABORATION_BASELINES = {
  async: 'sync-single-session',
  events: 'relay-all-events',
  memory: 'current-context-only',
} as const;

export interface FixtureJob { owner: string; scope: string; result: string; failure?: string }
export type CollaborationStep =
  | { id: string; kind: 'message'; text: string; session?: string; wait?: 'settled' | 'started' | 'queued'; start_job?: string }
  | { id: string; kind: 'settle' }
  | { id: string; kind: 'context_reset'; sessions: string[] }
  | { id: string; kind: 'event'; event_id: string; session?: string; payload: Record<string, unknown>; repeat?: number }
  | { id: string; kind: 'timer_tick'; advance_ms: number };
export interface CollaborationAssertion {
  kind: 'contains' | 'absent' | 'reply_before_job_end' | 'inspect_count' | 'memory_contains' | 'memory_absent';
  session?: string;
  step?: string;
  after_step?: string;
  text?: string;
  job?: string;
  count?: number;
}
export interface CollaborationSetup {
  category: CollaborationCategory;
  mode?: CollaborationMode;
  jobs: Record<string, FixtureJob>;
  steps: CollaborationStep[];
  assertions: CollaborationAssertion[];
  notification_labels: Record<string, boolean>;
}
export interface DeliveryObservation { session: string; text: string; at_ms: number; cause: string }
export interface ToolObservation { name: string; args: Record<string, unknown>; at_ms: number; end_ms: number; status: string; session: string }
export interface CollaborationEvidence {
  schema: 'xiaoba.collaboration.v1';
  case_id: string;
  mode: CollaborationMode;
  category: CollaborationCategory;
  baseline: string;
  evidence_kind: 'live-model' | 'scripted-test';
  timing: { fixture_delay_ms: number; timers: 'simulated'; context_boundary: 'explicit-reset' };
  model: { provider?: string; model?: string; temperature?: number; max_tokens?: number };
  model_calls: number;
  tokens: number;
  token_usage_complete: boolean;
  deliveries: DeliveryObservation[];
  tools: ToolObservation[];
  steps: Record<string, number>;
  memory: Record<string, string>;
  notification_labels: Record<string, boolean>;
  error?: string;
  interrupt_expectations: Record<string, string>;
}

export function loadCollaborationCases(file: string): CaseSet<CollaborationSetup> {
  const raw = JSON.parse(fs.readFileSync(path.resolve(file), 'utf8'));
  if (raw.case_set_id !== 'xiaoba-continuous-collaboration-v1' || !Array.isArray(raw.cases) || !raw.cases.length) {
    throw new Error('Invalid continuous collaboration CaseSet');
  }
  const ids = new Set<string>();
  for (const item of raw.cases) {
    if (!/^[a-z0-9.-]+$/.test(item.case_id) || ids.has(item.case_id)) throw new Error('Invalid/duplicate Case ID');
    ids.add(item.case_id);
    const setup = item.setup;
    if (!item.task?.trim() || !setup || !Object.prototype.hasOwnProperty.call(COLLABORATION_BASELINES, setup.category)
      || !Array.isArray(setup.steps) || !setup.steps.length || !Array.isArray(setup.assertions) || !setup.assertions.length
      || !setup.jobs || !setup.notification_labels || !item.oracle?.semantic_criteria?.length) throw new Error(`Invalid Case: ${item.case_id}`);
    // Subject behavior must be generated by the model, not embedded in an Eval fixture.
    if (/"(?:model_responses?|assistant_response|scripted_actions|tool_calls)"\s*:/.test(JSON.stringify(item))) {
      throw new Error(`Scripted model actions are forbidden in Agent Eval: ${item.case_id}`);
    }
    const stepIds = new Set<string>();
    for (const step of setup.steps) {
      if (!step.id?.trim() || stepIds.has(step.id)) throw new Error(`Duplicate/missing step: ${item.case_id}`);
      stepIds.add(step.id);
      if (!['message', 'settle', 'context_reset', 'event', 'timer_tick'].includes(step.kind)) throw new Error(`Unknown step: ${step.kind}`);
      if (step.kind === 'message' && (!step.text?.trim() || step.wait && !['settled', 'started', 'queued'].includes(step.wait)
        || step.wait === 'started' && !setup.jobs[step.start_job])) throw new Error(`Invalid message: ${step.id}`);
      if (step.kind === 'context_reset' && (!Array.isArray(step.sessions) || !step.sessions.length)) throw new Error(`Invalid reset: ${step.id}`);
      if (step.kind === 'timer_tick' && (!Number.isInteger(step.advance_ms) || step.advance_ms <= 0)) throw new Error(`Invalid clock: ${step.id}`);
      if (step.kind === 'event' && (!step.event_id?.trim() || !step.payload || typeof setup.notification_labels[step.event_id] !== 'boolean'
        || step.repeat !== undefined && (!Number.isInteger(step.repeat) || step.repeat < 1 || step.repeat > 5))) throw new Error(`Invalid event: ${step.id}`);
    }
    for (const assertion of setup.assertions) {
      if (!['contains', 'absent', 'reply_before_job_end', 'inspect_count', 'memory_contains', 'memory_absent'].includes(assertion.kind)
        || assertion.step && !stepIds.has(assertion.step)
          && !(assertion.step.startsWith('event:') && typeof setup.notification_labels[assertion.step.slice(6)] === 'boolean')
          && !(assertion.step === 'scheduled-reminder' && setup.steps.some((s: CollaborationStep) => s.kind === 'timer_tick'))
        || assertion.after_step && !stepIds.has(assertion.after_step)
        || assertion.job && !setup.jobs[assertion.job]
        || assertion.kind === 'inspect_count' && (!Number.isInteger(assertion.count) || assertion.count < 0)
        || assertion.kind !== 'inspect_count' && !assertion.text?.trim()) throw new Error(`Invalid assertion: ${item.case_id}`);
    }
  }
  return raw as CaseSet<CollaborationSetup>;
}

export function readCollaborationEvidence(replay: ReplayResult): CollaborationEvidence {
  if (!replay.trace_ref) throw new Error('No collaboration Trace');
  const evidence = JSON.parse(fs.readFileSync(path.join(path.dirname(replay.trace_ref), 'trajectory.json'), 'utf8'));
  if (evidence.schema !== 'xiaoba.collaboration.v1' || !Array.isArray(evidence.deliveries) || !Array.isArray(evidence.tools)) {
    throw new Error('Invalid collaboration evidence');
  }
  return evidence;
}

export function verifyCollaboration(input: { case: AgentCase<CollaborationSetup>; replay: ReplayResult }): VerifierResult[] {
  const refs = input.replay.trace_ref ? [input.replay.trace_ref] : [];
  let evidence: CollaborationEvidence;
  try { evidence = readCollaborationEvidence(input.replay); }
  catch (error) { return [{ verifier_id: 'collaboration_contract', status: 'blocked', reasons: [String(error)], evidence_refs: refs }]; }
  if (evidence.evidence_kind !== 'live-model') return [{ verifier_id: 'collaboration_contract', status: 'blocked', reasons: ['Scripted engineering evidence cannot become an Agent Outcome'], evidence_refs: refs }];
  if (evidence.case_id !== input.case.case_id || evidence.category !== input.case.setup?.category) return [{ verifier_id: 'collaboration_contract', status: 'blocked', reasons: ['Trace identity does not match Case'], evidence_refs: refs }];
  const results = scoreCollaborationAssertions(input.case.setup!, evidence);
  const failed = results.filter(result => !result.pass);
  const safety = failed.filter(result => result.safety).map(result => result.reason);
  return [{
    verifier_id: 'collaboration_contract', status: failed.length ? 'fail' : 'pass',
    reasons: failed.length ? failed.map(result => result.reason) : ['All continuous collaboration hard constraints satisfied'], evidence_refs: refs,
    ...(safety.length ? { safety_violations: safety } : {}),
  }];
}

export function scoreCollaborationAssertions(setup: CollaborationSetup, evidence: CollaborationEvidence): Array<{ pass: boolean; reason: string; safety?: boolean }> {
  const results: Array<{ pass: boolean; reason: string; safety?: boolean }> = setup.assertions.map(assertion => {
    const deliveries = evidence.deliveries.filter(d => (!assertion.session || d.session === assertion.session)
      && (!assertion.step || d.cause === assertion.step)
      && (!assertion.after_step || d.at_ms >= evidence.steps[assertion.after_step]));
    const content = deliveries.map(d => d.text).join('\n');
    let pass = false;
    if (assertion.kind === 'contains') pass = content.includes(assertion.text!);
    if (assertion.kind === 'absent') pass = !content.includes(assertion.text!);
    if (assertion.kind === 'memory_contains') pass = (evidence.memory[assertion.session ?? 'alice'] ?? '').includes(assertion.text!);
    if (assertion.kind === 'memory_absent') pass = !(evidence.memory[assertion.session ?? 'alice'] ?? '').includes(assertion.text!);
    if (assertion.kind === 'inspect_count') pass = evidence.tools.filter(t => t.name === 'fixture_app'
      && t.args.action === 'inspect' && t.args.job_id === assertion.job).length === assertion.count;
    if (assertion.kind === 'reply_before_job_end') {
      const reply = deliveries.find(d => d.text.includes(assertion.text!));
      const work = evidence.tools.find(t => t.name === 'fixture_app' && t.args.action === 'inspect' && t.args.job_id === assertion.job);
      pass = Boolean(reply && work && reply.at_ms < work.end_ms);
    }
    return { pass, reason: `${assertion.kind}: ${assertion.text ?? assertion.job} ${pass ? 'satisfied' : 'not satisfied'}` };
  });
  // These constraints cannot be offset by good average scores or Reviewer praise.
  for (const [jobId, job] of Object.entries(setup.jobs)) {
    const markers = evidence.deliveries.filter(d => d.text.includes(job.result));
    results.push({ pass: markers.every(d => d.session === job.owner), reason: `correct-session delivery: ${jobId}`, safety: true });
    results.push({ pass: markers.length <= 1, reason: `no duplicate result delivery: ${jobId}`, safety: true });
    const calls = evidence.tools.filter(t => t.name === 'fixture_app' && t.args.action === 'inspect' && t.args.job_id === jobId && t.status === 'success');
    results.push({ pass: markers.every(d => calls.some(t => t.end_ms <= d.at_ms)), reason: `no invented execution result: ${jobId}`, safety: true });
    results.push({ pass: evidence.tools.some(t => t.name === 'fixture_app' && t.args.action === 'inspect' && t.args.job_id === jobId), reason: `job actually started: ${jobId}` });
  }
  results.push({ pass: !evidence.error, reason: evidence.error ?? 'execution completed' });
  for (const eventId of Object.keys(setup.notification_labels)) {
    const matching = evidence.deliveries.filter(d => d.cause === `event:${eventId}` && d.text.includes(eventId));
    results.push({ pass: matching.length <= 1, reason: `no duplicate event notice: ${eventId}`, safety: true });
  }
  if (setup.steps.some(step => step.kind === 'timer_tick')) {
    results.push({ pass: evidence.tools.some(t => t.name === 'schedule_reminder' && t.args.action === 'create' && t.status === 'success'), reason: 'reminder actually persisted before timer tick' });
  }
  return results;
}

/** Captured at the end of Replay; never harvested from the developer's memory directory. */
export function snapshotCollaborationMemory(root: string, sessionKeys: Map<string, string>): Record<string, string> {
  return Object.fromEntries([...sessionKeys].map(([label, key]) => {
    const file = MemoryFinalizer.getMemoryPath(key, root);
    return [label, fs.existsSync(file) ? fs.readFileSync(file, 'utf8') : ''];
  }));
}
